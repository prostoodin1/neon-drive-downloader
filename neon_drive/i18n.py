def normalize_language(value: object, system_locale: str = "en") -> str:
    requested = str(value or "system").casefold().replace("_", "-")
    if requested == "system":
        requested = str(system_locale or "en").casefold().replace("_", "-")
    code = requested.split("-", 1)[0]
    return code if code in SUPPORTED_LANGUAGES else "en"


def translate(language: str, key: str, **values: object) -> str:
    selected = TRANSLATIONS.get(language, TRANSLATIONS["en"])
    template = selected.get(key, TRANSLATIONS["en"].get(key, key))
    return template.format(**values) if values else template
